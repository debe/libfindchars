//! Usage examples for findchars.
//!
//! Runnable examples live in the `examples/` directory:
//!
//! - `find_literals_and_positions` — detect ASCII literal groups and byte ranges.
//! - `find_utf8_characters` — detect 2-, 3-, and 4-byte UTF-8 codepoints.
//! - `parse_csv` — parse CSV with the SIMD-accelerated parser.
//!
//! Run one with:
//!
//! ```text
//! cargo run --example find_literals_and_positions -p findchars-examples
//! ```
